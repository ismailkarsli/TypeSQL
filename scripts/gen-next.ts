// Regenerates packages/core/src/engine/lexer/next.ts (token index successor table).
import { writeFileSync } from "node:fs";

const N = Number(process.argv[2] ?? 4096);
let s = `/**
 * Successor table for token indexes: \`Next[i]\` is \`i + 1\` for 0 ≤ i < ${N}.
 *
 * Index-based token access keeps the parser linear: slicing the token tuple with
 * \`...infer R\` is O(n) per operation and made the parser quadratic. The numeric index
 * signature lets \`Next[I]\` be a plain indexed access for a generic \`I\` (no conditional
 * type, no \`keyof\` comparison), while a literal \`I\` resolves to the exact successor.
 * Beyond ${N} tokens the result degrades to \`number\`; statements that long are out of scope.
 *
 * Generated by scripts/gen-next.ts.
 */
export interface Next {
  readonly [i: number]: number;
`;
for (let i = 0; i < N; i++) s += `  readonly ${i}: ${i + 1};\n`;
s += `}\n\n/** Highest token index supported by the parser. */\nexport type MaxTokens = ${N};\n`;
writeFileSync(
	new URL("../packages/core/src/engine/lexer/next.ts", import.meta.url),
	s,
);
