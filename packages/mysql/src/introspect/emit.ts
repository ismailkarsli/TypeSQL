import { propertyKey as key } from "@typesql/core/adapter";
import type {
	IntrospectedColumn,
	IntrospectedDatabase,
	IntrospectedRelation,
} from "./introspect.js";

export interface GenerateOptions {
	readonly typeName?: string;
	readonly importFrom?: string;
	readonly comments?: boolean;
}

const str = (s: string): string => JSON.stringify(s);

function doc(lines: readonly string[], indent: string): string {
	const text = lines
		.flatMap((l) => l.split("\n"))
		.map((l) => l.replace(/\*\//g, "*\\/").trimEnd());
	if (text.length === 0) return "";
	if (text.length === 1) return `${indent}/** ${text[0]} */\n`;
	return `${indent}/**\n${text.map((l) => `${indent} *${l ? ` ${l}` : ""}`).join("\n")}\n${indent} */\n`;
}

// `autoIncrement` and `generated` imply `hasDefault`.
const flagsOf = (c: IntrospectedColumn, view: boolean): string[] => [
	...(c.nullable ? ["nullable: true"] : []),
	...(c.hasDefault && !c.autoIncrement && !c.generated
		? ["hasDefault: true"]
		: []),
	`position: ${c.position}`,
	...(!view && c.autoIncrement ? ["autoIncrement: true"] : []),
	...(!view && c.generated ? ["generated: true"] : []),
	...(c.hidden ? ["hidden: true"] : []),
];

function columnNotes(c: IntrospectedColumn): string[] {
	const notes: string[] = [];
	if (c.comment) notes.push(c.comment);
	if (c.generated)
		notes.push(
			`\`GENERATED ALWAYS AS (${c.generated.expression}) ${c.generated.stored ? "STORED" : "VIRTUAL"}\`: cannot be written.`,
		);
	if (c.hidden) notes.push("`INVISIBLE`: left out of `SELECT *`.");
	return notes;
}

/** `8.4.3` → `MySQL 8.4`, `11.8.2-MariaDB-ubu2404` → `MariaDB 11.8`. */
const serverName = (db: IntrospectedDatabase): string =>
	`${db.mariadb ? "MariaDB" : "MySQL"} ${db.version.split(/[.-]/).slice(0, 2).join(".")}`;

export function generateSource(
	db: IntrospectedDatabase,
	options: GenerateOptions = {},
): string {
	const typeName = options.typeName ?? "DB";
	const comments = options.comments ?? true;
	const used = new Set<string>();

	const relation = (rel: IntrospectedRelation): string => {
		const view = rel.kind === "view";
		const cols = rel.columns.map((c) => {
			const flags = flagsOf(c, view).join("; ");
			let descriptor: string;
			if (c.enumValues) {
				used.add("Enum");
				const values = c.enumValues.map(str).join(" | ") || "never";
				descriptor = `Enum<${values}, { ${flags} }>`;
			} else {
				used.add("Col");
				descriptor = `Col<${str(c.type)}, { ${flags} }>`;
			}
			return `${comments ? doc(columnNotes(c), "    ") : ""}    ${key(c.name)}: ${descriptor};`;
		});
		const body = `{\n${cols.join("\n")}\n  }`;
		if (!view) return body;
		used.add("View");
		return `View<${body}>`;
	};

	const lines = db.relations.map((rel) => {
		const notes = comments
			? doc(
					[
						...(rel.comment ? [rel.comment] : []),
						...(rel.kind === "view" ? ["View."] : []),
					],
					"  ",
				)
			: "";
		return `${notes}  ${key(rel.name)}: ${relation(rel)};`;
	});
	const helpers = ["Col", "Enum", "View"].filter((h) => used.has(h));
	return [
		`// Generated by \`typesql introspect\` from ${serverName(db)}. Do not edit.`,
		...(helpers.length > 0
			? [
					`import type { ${helpers.join(", ")} } from ${str(options.importFrom ?? "@typesql/core/mysql")};`,
				]
			: []),
		"",
		`export interface ${key(typeName)} {`,
		...lines,
		"}",
		"",
	].join("\n");
}
