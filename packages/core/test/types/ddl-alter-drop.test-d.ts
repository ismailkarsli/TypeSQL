import { expectTypeOf, test } from "vitest";
import type { ApplyDdl, Col, Generated, Nullable, NullableGenerated, SqlError, View } from "../../src/index.js";

interface DB {
  users: { id: Generated<"int4">; email: Col<"text">; name: Nullable<"text"> };
  posts: { id: Generated<"int8">; title: Col<"text"> };
  active_users: View<{ id: Col<"int4">; email: Col<"text"> }>;
  app: { events: { id: Col<"int4"> } };
}
type Users = DB["users"];
type A<Q extends string> = ApplyDdl<DB, Q>;

test("ADD COLUMN", () => {
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN age int NOT NULL DEFAULT 0">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text">; name: Nullable<"text">; age: Generated<"int4"> }>();
  expectTypeOf<A<"ALTER TABLE users ADD age int">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text">; name: Nullable<"text">; age: Nullable<"int4"> }>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN k serial, ADD COLUMN tags text[] DEFAULT '{}', ADD COLUMN ref int REFERENCES posts (id) ON DELETE CASCADE">["users"]>().toEqualTypeOf<{
    id: Generated<"int4">; email: Col<"text">; name: Nullable<"text">; k: Generated<"int4">; tags: NullableGenerated<"text[]">; ref: Nullable<"int4">;
  }>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN IF NOT EXISTS email int">>().toEqualTypeOf<DB>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN p int PRIMARY KEY">["users"]["p"]>().toEqualTypeOf<Col<"int4">>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN i int GENERATED BY DEFAULT AS IDENTITY">["users"]["i"]>().toEqualTypeOf<Generated<"int4">>();
});

test("DROP COLUMN", () => {
  expectTypeOf<A<"ALTER TABLE users DROP COLUMN name">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users DROP name CASCADE">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users DROP COLUMN IF EXISTS nope RESTRICT">["users"]>().toEqualTypeOf<Users>();
  // drops run before adds (Postgres applies ALTER TABLE sub-commands in passes)
  expectTypeOf<A<"ALTER TABLE users DROP COLUMN name, ADD COLUMN name int">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text">; name: Nullable<"int4"> }>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN x int, DROP COLUMN x">>().toEqualTypeOf<SqlError<'column "x" of relation "users" does not exist', 5>>();
});

test("RENAME COLUMN, RENAME TO, SET SCHEMA", () => {
  expectTypeOf<A<"ALTER TABLE users RENAME COLUMN name TO display_name">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text">; display_name: Nullable<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users RENAME name TO nick">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Col<"text">; nick: Nullable<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users RENAME TO members">>().toEqualTypeOf<{ members: Users; posts: DB["posts"]; active_users: DB["active_users"]; app: DB["app"] }>();
  expectTypeOf<A<"ALTER TABLE users SET SCHEMA app">>().toEqualTypeOf<{ posts: DB["posts"]; active_users: DB["active_users"]; app: { events: { id: Col<"int4"> }; users: Users } }>();
  expectTypeOf<A<"ALTER TABLE app.events SET SCHEMA public">>().toEqualTypeOf<{ users: Users; posts: DB["posts"]; active_users: DB["active_users"]; app: {}; events: { id: Col<"int4"> } }>();
  expectTypeOf<A<"ALTER TABLE app.events RENAME TO evts">["app"]>().toEqualTypeOf<{ evts: { id: Col<"int4"> } }>();
});

test("ALTER COLUMN TYPE / SET / DROP", () => {
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN id TYPE bigint">["users"]>().toEqualTypeOf<{ id: Generated<"int8">; email: Col<"text">; name: Nullable<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN email SET DATA TYPE varchar(100) COLLATE \"C\", ALTER name TYPE int USING length(name)">["users"]>().toEqualTypeOf<{
    id: Generated<"int4">; email: Col<"varchar">; name: Nullable<"int4">;
  }>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN name SET NOT NULL, ALTER COLUMN email DROP NOT NULL">["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Nullable<"text">; name: Col<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN name SET DEFAULT 'anon', ALTER COLUMN id DROP DEFAULT">["users"]>().toEqualTypeOf<{ id: Col<"int4">; email: Col<"text">; name: NullableGenerated<"text"> }>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN email ADD GENERATED ALWAYS AS IDENTITY">["users"]["email"]>().toEqualTypeOf<Generated<"text">>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN id DROP IDENTITY IF EXISTS">["users"]["id"]>().toEqualTypeOf<Col<"int4">>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN id DROP EXPRESSION">["users"]["id"]>().toEqualTypeOf<Col<"int4">>();
  // SET DEFAULT runs after ADD COLUMN; DROP NOT NULL runs before it
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN x int, ALTER COLUMN x SET DEFAULT 1">["users"]["x"]>().toEqualTypeOf<NullableGenerated<"int4">>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN x int NOT NULL, ALTER COLUMN x DROP NOT NULL">>().toEqualTypeOf<SqlError<'column "x" of relation "users" does not exist', 5>>();
});

test("ADD PRIMARY KEY makes the columns NOT NULL", () => {
  expectTypeOf<A<"ALTER TABLE users ADD PRIMARY KEY (name)">["users"]["name"]>().toEqualTypeOf<Col<"text">>();
  expectTypeOf<A<"ALTER TABLE users ADD CONSTRAINT users_pk PRIMARY KEY (email, name) DEFERRABLE">["users"]["name"]>().toEqualTypeOf<Col<"text">>();
});

test("multiple actions, IF EXISTS, ONLY, no-op actions", () => {
  expectTypeOf<A<`ALTER TABLE ONLY users
      ADD COLUMN age int,
      DROP COLUMN name,
      ALTER COLUMN email DROP NOT NULL,
      ADD CONSTRAINT users_email_key UNIQUE (email),
      ADD CONSTRAINT fk FOREIGN KEY (age) REFERENCES posts (id),
      ADD CHECK (age > 0),
      DROP CONSTRAINT IF EXISTS old_check,
      VALIDATE CONSTRAINT fk,
      ALTER COLUMN email SET STATISTICS 100,
      ENABLE ROW LEVEL SECURITY,
      OWNER TO admin`>["users"]>().toEqualTypeOf<{ id: Generated<"int4">; email: Nullable<"text">; age: Nullable<"int4"> }>();
  expectTypeOf<A<"ALTER TABLE IF EXISTS nope ADD COLUMN x int">>().toEqualTypeOf<DB>();
  expectTypeOf<A<"ALTER TABLE users RENAME CONSTRAINT a TO b">["users"]>().toEqualTypeOf<Users>();
  expectTypeOf<A<"ALTER TABLE app.events ADD COLUMN at timestamptz NOT NULL DEFAULT now()">["app"]>().toEqualTypeOf<{ events: { id: Col<"int4">; at: Generated<"timestamptz"> } }>();
});

test("ALTER on views: renames and defaults only", () => {
  expectTypeOf<A<"ALTER VIEW active_users RENAME COLUMN email TO mail">["active_users"]>().toEqualTypeOf<View<{ id: Col<"int4">; mail: Col<"text"> }>>();
  expectTypeOf<A<"ALTER TABLE active_users RENAME TO members">["members"]>().toEqualTypeOf<DB["active_users"]>();
  expectTypeOf<A<"ALTER VIEW active_users ALTER COLUMN id SET DEFAULT 0">["active_users"]>().toEqualTypeOf<View<{ id: Generated<"int4">; email: Col<"text"> }>>();
  expectTypeOf<A<"ALTER TABLE active_users ADD COLUMN x int">>().toEqualTypeOf<SqlError<'ALTER action ADD COLUMN cannot be performed on relation "active_users"', 2>>();
  expectTypeOf<A<"ALTER TABLE active_users ALTER COLUMN id SET NOT NULL">>().toEqualTypeOf<SqlError<'ALTER action ALTER COLUMN ... SET NOT NULL cannot be performed on relation "active_users"', 2>>();
});

test("DROP TABLE", () => {
  expectTypeOf<A<"DROP TABLE posts">>().toEqualTypeOf<{ users: Users; active_users: DB["active_users"]; app: DB["app"] }>();
  expectTypeOf<A<"DROP TABLE IF EXISTS nope, posts, users CASCADE">>().toEqualTypeOf<{ active_users: DB["active_users"]; app: DB["app"] }>();
  expectTypeOf<A<"DROP TABLE app.events">["app"]>().toEqualTypeOf<{}>();
  expectTypeOf<A<"DROP TABLE nope">>().toEqualTypeOf<SqlError<'table "nope" does not exist', 2>>();
  expectTypeOf<A<"DROP TABLE users, nope">>().toEqualTypeOf<SqlError<'table "nope" does not exist', 4>>();
  expectTypeOf<A<"DROP TABLE active_users">>().toEqualTypeOf<SqlError<'"active_users" is not a table', 2>>();
});

test("errors", () => {
  expectTypeOf<A<"ALTER TABLE nope ADD COLUMN x int">>().toEqualTypeOf<SqlError<'relation "nope" does not exist', 2>>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN email text">>().toEqualTypeOf<SqlError<'column "email" of relation "users" already exists', 5>>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN a int NULL NOT NULL">>().toEqualTypeOf<SqlError<'conflicting NULL/NOT NULL declarations for column "a" of table "users"', 8>>();
  expectTypeOf<A<"ALTER TABLE users DROP COLUMN nope">>().toEqualTypeOf<SqlError<'column "nope" of relation "users" does not exist', 5>>();
  expectTypeOf<A<"ALTER TABLE users RENAME COLUMN nope TO x">>().toEqualTypeOf<SqlError<'column "nope" does not exist', 5>>();
  expectTypeOf<A<"ALTER TABLE users RENAME COLUMN name TO email">>().toEqualTypeOf<SqlError<'column "email" of relation "users" already exists', 7>>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN nope SET NOT NULL">>().toEqualTypeOf<SqlError<'column "nope" of relation "users" does not exist', 5>>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN nope TYPE int">>().toEqualTypeOf<SqlError<'column "nope" of relation "users" does not exist', 5>>();
  expectTypeOf<A<"ALTER TABLE users ADD PRIMARY KEY (nope)">>().toEqualTypeOf<SqlError<'column "nope" of relation "users" does not exist', 7>>();
  expectTypeOf<A<"ALTER TABLE users RENAME TO posts">>().toEqualTypeOf<SqlError<'relation "posts" already exists', 5>>();
  expectTypeOf<A<"ALTER TABLE users SET SCHEMA nope">>().toEqualTypeOf<SqlError<'schema "nope" does not exist', 5>>();
  expectTypeOf<ApplyDdl<{ users: Users; app: { users: Users } }, "ALTER TABLE users SET SCHEMA app">>().toEqualTypeOf<SqlError<'relation "users" already exists in schema "app"', 2>>();
  expectTypeOf<A<"ALTER TABLE users ALTER COLUMN name ADD GENERATED ALWAYS AS IDENTITY">>().toEqualTypeOf<SqlError<'column "name" of relation "users" must be declared NOT NULL before identity can be added', 5>>();
  // RENAME and SET SCHEMA cannot be combined with other actions
  expectTypeOf<A<"ALTER TABLE users RENAME TO x, ADD COLUMN y int">>().toEqualTypeOf<SqlError<"syntax error at or near ,", 6>>();
  expectTypeOf<A<"ALTER TABLE users ADD COLUMN y int, RENAME TO x">>().toEqualTypeOf<SqlError<"syntax error at or near rename", 8>>();
  expectTypeOf<A<"ALTER TABLE users FROB">>().toEqualTypeOf<SqlError<"syntax error: expected ALTER TABLE action at or near frob", 3>>();
});
