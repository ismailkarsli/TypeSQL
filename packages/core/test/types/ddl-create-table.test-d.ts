test("CREATE TABLE AS: columns from the query, all nullable, no defaults", () => {
	type DB = {
		users: {
			id: Generated<"int4">;
			email: Col<"text">;
			name: Nullable<"text">;
		};
	};
	expectTypeOf<
		ApplyDdl<
			DB,
			"CREATE TABLE copy AS SELECT id, email, name, 1 AS one FROM users"
		>["copy"]
	>().toEqualTypeOf<{
		id: Nullable<"int4">;
		email: Nullable<"text">;
		name: Nullable<"text">;
		one: Nullable<"int4">;
	}>();
	expectTypeOf<
		ApplyDdl<
			DB,
			"CREATE TABLE IF NOT EXISTS copy (a, b) AS SELECT id, email, name FROM users WITH NO DATA"
		>["copy"]
	>().toEqualTypeOf<{
		a: Nullable<"int4">;
		b: Nullable<"text">;
		name: Nullable<"text">;
	}>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE IF NOT EXISTS users AS SELECT 1 AS x">
	>().toEqualTypeOf<DB>();
	expectTypeOf<
		ApplyDdl<
			DB,
			"CREATE TABLE s AS SELECT u.*, count(*) OVER () AS n FROM users u"
		>["s"]
	>().toEqualTypeOf<{
		id: Nullable<"int4">;
		email: Nullable<"text">;
		name: Nullable<"text">;
		n: Nullable<"int8">;
	}>();
	// an untyped NULL is stored as text, in tables and views (Postgres resolves it so)
	type N = ApplyDdl<
		{},
		"CREATE TABLE t AS SELECT NULL AS x; CREATE VIEW v AS SELECT NULL AS x"
	>;
	expectTypeOf<N["t"]>().toEqualTypeOf<{ x: Nullable<"text"> }>();
	expectTypeOf<N["v"]>().toEqualTypeOf<View<{ x: Nullable<"text"> }>>();
	// a name with nothing that makes a table; an error in the query
	expectTypeOf<D<"CREATE TABLE t foo">>().toEqualTypeOf<
		SqlError<
			'syntax error: expected "(", AS, OF or PARTITION OF at or near foo',
			3
		>
	>();
	expectTypeOf<D<"CREATE TABLE t AS SELECT +">>().toEqualTypeOf<
		SqlError<"syntax error at end of input", 6>
	>();
});

test("errors", () => {
	type DB = { users: { id: Col<"int4"> } };
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE users (id int)">>().toEqualTypeOf<
		SqlError<'relation "users" already exists', 2>
	>();
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE nope.t (id int)">>().toEqualTypeOf<
		SqlError<'schema "nope" does not exist', 2>
	>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a int, b text, a text)">
	>().toEqualTypeOf<SqlError<'column "a" specified more than once', 10>>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a int, PRIMARY KEY (b))">
	>().toEqualTypeOf<SqlError<'column "b" named in key does not exist', 10>>();
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (LIKE nope)">>().toEqualTypeOf<
		SqlError<'relation "nope" does not exist', 5>
	>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (LIKE users, id int)">
	>().toEqualTypeOf<SqlError<'column "id" specified more than once', 7>>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a int NULL NOT NULL)">
	>().toEqualTypeOf<
		SqlError<
			'conflicting NULL/NOT NULL declarations for column "a" of table "t"',
			7
		>
	>();
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a serial NULL)">>().toEqualTypeOf<
		SqlError<
			'conflicting NULL/NOT NULL declarations for column "a" of table "t"',
			6
		>
	>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a int GENERATED ALWAYS AS IDENTITY NULL)">
	>().toEqualTypeOf<
		SqlError<
			'conflicting NULL/NOT NULL declarations for column "a" of table "t"',
			10
		>
	>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t AS SELECT nope FROM users">
	>().toEqualTypeOf<SqlError<'column "nope" does not exist', 5>>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t AS SELECT 1 AS a, 2 AS a">
	>().toEqualTypeOf<SqlError<'column "a" specified more than once', 11>>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a, b) AS SELECT 1 AS x">
	>().toEqualTypeOf<SqlError<"too many column names were specified", 0>>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE t (a int PRIMARY KEY, b int, PRIMARY KEY (b))">
	>().toEqualTypeOf<
		SqlError<'multiple primary keys for table "t" are not allowed', 2>
	>();
	expectTypeOf<
		ApplyDdl<DB, "CREATE TABLE c () INHERITS (nope)">
	>().toEqualTypeOf<SqlError<'relation "nope" does not exist', 7>>();
	expectTypeOf<
		ApplyDdl<{ app: { t: { id: Col<"int4"> } } }, "CREATE TABLE app (x int)">
	>().toEqualTypeOf<
		SqlError<
			'cannot create relation "app": a schema with that name exists (TypeSQL keeps schemas and public relations in one object)',
			2
		>
	>();
	// syntax errors carry the index of the offending token
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int foo)">>().toEqualTypeOf<
		SqlError<"syntax error: expected column constraint at or near foo", 6>
	>();
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int,)">>().toEqualTypeOf<
		SqlError<"syntax error: expected column name at or near )", 7>
	>();
	expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int) junk">>().toEqualTypeOf<
		SqlError<"syntax error at or near junk", 7>
	>();
	expectTypeOf<
		ApplyDdl<
			DB,
			"CREATE TABLE t (id int) PARTITION BY RANGE (id) WITH (fillfactor = 70) TABLESPACE ts"
		>["t"]
	>().toEqualTypeOf<{ id: Nullable<"int4"> }>();
	expectTypeOf<
		ApplyDdl<
			DB,
			"CREATE TABLE t2 WITH (fillfactor = 70) AS SELECT 1 AS a WITH DATA"
		>["t2"]
	>().toEqualTypeOf<{ a: Nullable<"int4"> }>();
});

