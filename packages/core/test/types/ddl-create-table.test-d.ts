import { expectTypeOf, test } from "vitest";
import type { ApplyDdl, Col, Generated, Nullable, NullableGenerated, SqlError, View } from "../../src/index.js";

/** Apply DDL to an empty database. */
type D<Q extends string> = ApplyDdl<{}, Q>;

test("NOT NULL, NULL, DEFAULT, PRIMARY KEY", () => {
  expectTypeOf<D<`CREATE TABLE users (
    id int PRIMARY KEY,
    email text NOT NULL,
    name text,
    bio text NULL,
    age int NOT NULL DEFAULT 0,
    score int DEFAULT 0 NOT NULL,
    nick varchar(20) DEFAULT 'x' || 'y',
    created_at timestamptz NOT NULL DEFAULT now(),
    flag boolean DEFAULT false
  )`>>().toEqualTypeOf<{
    users: {
      id: Col<"int4">;
      email: Col<"text">;
      name: Nullable<"text">;
      bio: Nullable<"text">;
      age: Generated<"int4">;
      score: Generated<"int4">;
      nick: NullableGenerated<"varchar">;
      created_at: Generated<"timestamptz">;
      flag: NullableGenerated<"bool">;
    };
  }>();
  // PRIMARY KEY wins over an explicit NULL (verified on Postgres 17)
  expectTypeOf<D<"CREATE TABLE t (a int NULL PRIMARY KEY)">>().toEqualTypeOf<{ t: { a: Col<"int4"> } }>();
});

test("serial types are NOT NULL with a default", () => {
  expectTypeOf<D<"CREATE TABLE t (a serial, b serial4, c bigserial, d serial8, e smallserial, f serial2, g serial PRIMARY KEY)">>().toEqualTypeOf<{
    t: { a: Generated<"int4">; b: Generated<"int4">; c: Generated<"int8">; d: Generated<"int8">; e: Generated<"int2">; f: Generated<"int2">; g: Generated<"int4"> };
  }>();
});

test("identity and generated columns", () => {
  expectTypeOf<D<`CREATE TABLE t (
    a int GENERATED ALWAYS AS IDENTITY,
    b bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5),
    c int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first text NOT NULL,
    last text,
    full_name text GENERATED ALWAYS AS (first || ' ' || last) STORED,
    first_upper text NOT NULL GENERATED ALWAYS AS (upper(first)) STORED
  )`>>().toEqualTypeOf<{
    t: {
      a: Generated<"int4">;
      b: Generated<"int8">;
      c: Generated<"int4">;
      first: Col<"text">;
      last: Nullable<"text">;
      full_name: NullableGenerated<"text">;
      first_upper: Generated<"text">;
    };
  }>();
});

test("table-level PRIMARY KEY and named constraints", () => {
  expectTypeOf<D<"CREATE TABLE m (a int, b int, c int, PRIMARY KEY (a, b))">>().toEqualTypeOf<{
    m: { a: Col<"int4">; b: Col<"int4">; c: Nullable<"int4"> };
  }>();
  expectTypeOf<D<"CREATE TABLE m (a int, b text, CONSTRAINT m_pk PRIMARY KEY (b), CONSTRAINT m_a_check CHECK (a > 0))">>().toEqualTypeOf<{
    m: { a: Nullable<"int4">; b: Col<"text"> };
  }>();
});

test("REFERENCES, CHECK, UNIQUE, EXCLUDE, FOREIGN KEY and other clauses are ignored", () => {
  expectTypeOf<D<`CREATE TABLE posts (
    id bigserial CONSTRAINT posts_pk PRIMARY KEY,
    author_id int NOT NULL REFERENCES users (id) ON DELETE CASCADE ON UPDATE NO ACTION,
    editor_id int CONSTRAINT fk_editor REFERENCES users ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    slug text UNIQUE NOT NULL,
    title text COLLATE "C" CHECK (length(title) > 0),
    rating int CHECK (rating BETWEEN 1 AND 5) NO INHERIT,
    period tstzrange,
    UNIQUE (author_id, slug),
    UNIQUE NULLS NOT DISTINCT (title) INCLUDE (rating) WITH (fillfactor = 70),
    CHECK (rating IS NULL OR rating > 0),
    FOREIGN KEY (author_id) REFERENCES users (id) MATCH FULL,
    EXCLUDE USING gist (period WITH &&)
  ) WITH (fillfactor = 90) TABLESPACE pg_default`>>().toEqualTypeOf<{
    posts: {
      id: Generated<"int8">;
      author_id: Col<"int4">;
      editor_id: Nullable<"int4">;
      slug: Col<"text">;
      title: Nullable<"text">;
      rating: Nullable<"int4">;
      period: Nullable<"tstzrange">;
    };
  }>();
});

test("type names are normalized; arrays", () => {
  expectTypeOf<D<`CREATE TABLE t (
    a integer, b bigint, c smallint, d boolean, e double precision, f real,
    g character varying(255), h varchar, i char(3), j numeric(10, 2), k decimal,
    l timestamp with time zone, m timestamp(3) without time zone, n time with time zone,
    o text[], p int[][], q integer ARRAY, r varchar(10)[], s jsonb, t uuid, u bytea, v interval
  )`>>().toEqualTypeOf<{
    t: {
      a: Nullable<"int4">; b: Nullable<"int8">; c: Nullable<"int2">; d: Nullable<"bool">; e: Nullable<"float8">; f: Nullable<"float4">;
      g: Nullable<"varchar">; h: Nullable<"varchar">; i: Nullable<"bpchar">; j: Nullable<"numeric">; k: Nullable<"numeric">;
      l: Nullable<"timestamptz">; m: Nullable<"timestamp">; n: Nullable<"timetz">;
      o: Nullable<"text[]">; p: Nullable<"int4[]">; q: Nullable<"int4[]">; r: Nullable<"varchar[]">; s: Nullable<"jsonb">; t: Nullable<"uuid">; u: Nullable<"bytea">; v: Nullable<"interval">;
    };
  }>();
});

test("quoted identifiers keep their case; unquoted names fold", () => {
  expectTypeOf<D<`CREATE TABLE "UserAccounts" ("Id" int NOT NULL, "select" text, MixedCase int)`>>().toEqualTypeOf<{
    UserAccounts: { Id: Col<"int4">; select: Nullable<"text">; mixedcase: Nullable<"int4"> };
  }>();
});

test("schema-qualified names, temp/unlogged tables, IF NOT EXISTS", () => {
  expectTypeOf<D<"CREATE SCHEMA app; CREATE TABLE app.users (id int NOT NULL); CREATE TABLE public.logs (msg text)">>().toEqualTypeOf<{
    app: { users: { id: Col<"int4"> } };
    logs: { msg: Nullable<"text"> };
  }>();
  expectTypeOf<D<"CREATE TEMP TABLE a (x int); CREATE UNLOGGED TABLE b (y int); CREATE TABLE e ()">>().toEqualTypeOf<{
    a: { x: Nullable<"int4"> };
    b: { y: Nullable<"int4"> };
    e: {};
  }>();
  type DB = { users: { id: Col<"int4"> } };
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE IF NOT EXISTS users (other text)">>().toEqualTypeOf<DB>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE IF NOT EXISTS logs (msg text)">>().toEqualTypeOf<{ users: { id: Col<"int4"> }; logs: { msg: Nullable<"text"> } }>();
});

test("LIKE copies columns and NOT NULL; defaults only with INCLUDING", () => {
  type DB = { src: { id: Generated<"int4">; name: Col<"text">; note: NullableGenerated<"text"> } };
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE dst (LIKE src)">["dst"]>().toEqualTypeOf<{ id: Col<"int4">; name: Col<"text">; note: Nullable<"text"> }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE dst (LIKE src INCLUDING DEFAULTS)">["dst"]>().toEqualTypeOf<{ id: Generated<"int4">; name: Col<"text">; note: NullableGenerated<"text"> }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE dst (LIKE src INCLUDING ALL EXCLUDING DEFAULTS, extra int)">["dst"]>().toEqualTypeOf<{ id: Col<"int4">; name: Col<"text">; note: Nullable<"text">; extra: Nullable<"int4"> }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE dst (pre int, LIKE src INCLUDING ALL)">["dst"]>().toEqualTypeOf<{ pre: Nullable<"int4">; id: Generated<"int4">; name: Col<"text">; note: NullableGenerated<"text"> }>();
});

test("INHERITS and PARTITION OF copy the parent's columns with their defaults", () => {
  type DB = { parent: { id: Generated<"int4">; k: Col<"int4">; n: Nullable<"int4"> } };
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE child (extra text, n int NOT NULL) INHERITS (parent)">["child"]>().toEqualTypeOf<{
    id: Generated<"int4">; k: Col<"int4">; n: Col<"int4">; extra: Nullable<"text">;
  }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE p1 PARTITION OF parent FOR VALUES FROM (1) TO (10)">["p1"]>().toEqualTypeOf<DB["parent"]>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE child (k text) INHERITS (parent)">>().toEqualTypeOf<SqlError<'column "k" has a type conflict', 4>>();
});

test("CREATE TABLE AS: columns from the query, all nullable, no defaults", () => {
  type DB = { users: { id: Generated<"int4">; email: Col<"text">; name: Nullable<"text"> } };
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE copy AS SELECT id, email, name, 1 AS one FROM users">["copy"]>().toEqualTypeOf<{
    id: Nullable<"int4">; email: Nullable<"text">; name: Nullable<"text">; one: Nullable<"int4">;
  }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE IF NOT EXISTS copy (a, b) AS SELECT id, email, name FROM users WITH NO DATA">["copy"]>().toEqualTypeOf<{
    a: Nullable<"int4">; b: Nullable<"text">; name: Nullable<"text">;
  }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE IF NOT EXISTS users AS SELECT 1 AS x">>().toEqualTypeOf<DB>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE s AS SELECT u.*, count(*) OVER () AS n FROM users u">["s"]>().toEqualTypeOf<{
    id: Nullable<"int4">; email: Nullable<"text">; name: Nullable<"text">; n: Nullable<"int8">;
  }>();
});

test("errors", () => {
  type DB = { users: { id: Col<"int4"> } };
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE users (id int)">>().toEqualTypeOf<SqlError<'relation "users" already exists', 2>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE nope.t (id int)">>().toEqualTypeOf<SqlError<'schema "nope" does not exist', 2>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a int, b text, a text)">>().toEqualTypeOf<SqlError<'column "a" specified more than once', 10>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a int, PRIMARY KEY (b))">>().toEqualTypeOf<SqlError<'column "b" named in key does not exist', 10>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (LIKE nope)">>().toEqualTypeOf<SqlError<'relation "nope" does not exist', 5>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (LIKE users, id int)">>().toEqualTypeOf<SqlError<'column "id" specified more than once', 7>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a int NULL NOT NULL)">>().toEqualTypeOf<SqlError<'conflicting NULL/NOT NULL declarations for column "a" of table "t"', 7>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a serial NULL)">>().toEqualTypeOf<SqlError<'conflicting NULL/NOT NULL declarations for column "a" of table "t"', 6>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a int GENERATED ALWAYS AS IDENTITY NULL)">>().toEqualTypeOf<SqlError<'conflicting NULL/NOT NULL declarations for column "a" of table "t"', 10>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t AS SELECT nope FROM users">>().toEqualTypeOf<SqlError<'column "nope" does not exist', 5>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t AS SELECT 1 AS a, 2 AS a">>().toEqualTypeOf<SqlError<'column "a" specified more than once', 11>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a, b) AS SELECT 1 AS x">>().toEqualTypeOf<SqlError<"too many column names were specified", 0>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (a int PRIMARY KEY, b int, PRIMARY KEY (b))">>().toEqualTypeOf<SqlError<'multiple primary keys for table "t" are not allowed', 2>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE c () INHERITS (nope)">>().toEqualTypeOf<SqlError<'relation "nope" does not exist', 7>>();
  expectTypeOf<ApplyDdl<{ app: { t: { id: Col<"int4"> } } }, "CREATE TABLE app (x int)">>().toEqualTypeOf<SqlError<'cannot create relation "app": a schema with that name exists (TypeSQL keeps schemas and public relations in one object)', 2>>();
  // syntax errors carry the index of the offending token
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int foo)">>().toEqualTypeOf<SqlError<"syntax error: expected column constraint at or near foo", 6>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int,)">>().toEqualTypeOf<SqlError<"syntax error: expected column name at or near )", 7>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int) junk">>().toEqualTypeOf<SqlError<"syntax error at or near junk", 7>>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t (id int) PARTITION BY RANGE (id) WITH (fillfactor = 70) TABLESPACE ts">["t"]>().toEqualTypeOf<{ id: Nullable<"int4"> }>();
  expectTypeOf<ApplyDdl<DB, "CREATE TABLE t2 WITH (fillfactor = 70) AS SELECT 1 AS a WITH DATA">["t2"]>().toEqualTypeOf<{ a: Nullable<"int4"> }>();
});

test("float(p) maps to float4 for p <= 24, float8 otherwise", () => {
  type S = ApplyDdl<{}, "CREATE TABLE f (a float, b float(10), c float(24), d float(25), e real, g double precision)">;
  expectTypeOf<S["f"]["a"]["type"]>().toEqualTypeOf<"float8">();
  expectTypeOf<S["f"]["b"]["type"]>().toEqualTypeOf<"float4">();
  expectTypeOf<S["f"]["c"]["type"]>().toEqualTypeOf<"float4">();
  expectTypeOf<S["f"]["d"]["type"]>().toEqualTypeOf<"float8">();
  expectTypeOf<S["f"]["e"]["type"]>().toEqualTypeOf<"float4">();
  expectTypeOf<S["f"]["g"]["type"]>().toEqualTypeOf<"float8">();
});
