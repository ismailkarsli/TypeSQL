/** Apply DDL to an empty database. */
type D<Q extends string> = ApplyDdl<{}, Q>;

test("NOT NULL, NULL, DEFAULT, PRIMARY KEY", () => {
	expectTypeOf<
		D<`CREATE TABLE users (
    id int PRIMARY KEY,
    email text NOT NULL,
    name text,
    bio text NULL,
    age int NOT NULL DEFAULT 0,
    score int DEFAULT 0 NOT NULL,
    nick varchar(20) DEFAULT 'x' || 'y',
    created_at timestamptz NOT NULL DEFAULT now(),
    flag boolean DEFAULT false
  )`>
	>().toEqualTypeOf<{
		users: {
			id: Col<"int4">;
			email: Col<"text">;
			name: Nullable<"text">;
			bio: Nullable<"text">;
			age: Generated<"int4">;
			score: Generated<"int4">;
			nick: NullableGenerated<"varchar">;
			created_at: Generated<"timestamptz">;
			flag: NullableGenerated<"bool">;
		};
	}>();
	// PRIMARY KEY wins over an explicit NULL (verified on Postgres 17)
	expectTypeOf<D<"CREATE TABLE t (a int NULL PRIMARY KEY)">>().toEqualTypeOf<{
		t: { a: Col<"int4"> };
	}>();
});

