import type { IntrospectedDatabase } from "./introspect.js";

export interface GenerateOptions {
	readonly typeName?: string;
	readonly importFrom?: string;
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string): string =>
	IDENT.test(name) ? name : JSON.stringify(name);

export function generateSource(
	db: IntrospectedDatabase,
	opts: GenerateOptions = {},
): string {
	const typeName = opts.typeName ?? "DB";
	const importFrom = opts.importFrom ?? "@typesql/core/sqlite";
	const views = db.relations.some((r) => r.kind === "view");
	const lines = [
		`// Generated by \`typesql introspect\` from SQLite ${db.version}. Do not edit.`,
		`import type { Col${views ? ", View" : ""} } from ${JSON.stringify(importFrom)};`,
		"",
		`export interface ${typeName} {`,
	];
	for (const r of db.relations) {
		const cols = r.columns.map((c) => {
			const flags = [
				c.nullable ? "nullable: true" : "",
				c.hasDefault && !c.generated && !c.hidden ? "hasDefault: true" : "",
				c.hidden ? "hidden: true" : `position: ${c.position}`,
				c.rowid ? "rowid: true" : "",
				c.generated ? "generated: true" : "",
			].filter(Boolean);
			return `\t\t${key(c.name)}: Col<${JSON.stringify(c.type)}, { ${flags.join("; ")} }>;`;
		});
		if (r.kind === "view") {
			lines.push(`\t${key(r.name)}: View<{`, ...cols, "\t}>;");
		} else {
			lines.push(`\t${key(r.name)}: {`, ...cols, "\t};");
		}
	}
	lines.push("}", "");
	return lines.join("\n");
}
