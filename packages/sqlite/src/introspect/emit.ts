import { propertyKey as key, schemaWriter } from "@typesql/core/adapter";
import type { IntrospectedDatabase } from "./introspect.js";

export interface GenerateOptions {
	readonly typeName?: string;
	readonly importFrom?: string;
}

export function generateSource(
	db: IntrospectedDatabase,
	opts: GenerateOptions = {},
): string {
	const write = schemaWriter("sqlite");
	const lines: string[] = [];
	for (const r of db.relations) {
		const cols = r.columns.map(
			(c) =>
				`\t\t${key(c.name)}: ${write.col(c.type, {
					nullable: c.nullable,
					hasDefault: c.hasDefault,
					// A hidden column has no place in `SELECT *`.
					position: c.hidden ? undefined : c.position,
					rowid: c.rowid,
					generated: c.generated,
					hidden: c.hidden,
				})};`,
		);
		const body = `{\n${cols.join("\n")}\n\t}`;
		lines.push(
			`\t${key(r.name)}: ${r.kind === "view" ? write.view(body) : body};`,
		);
	}
	return write.module({
		header: `Generated by \`typesql introspect\` from SQLite ${db.version}. Do not edit.`,
		members: lines,
		typeName: opts.typeName,
		importFrom: opts.importFrom,
	});
}
