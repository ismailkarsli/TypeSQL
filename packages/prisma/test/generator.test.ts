test("outputFile: a .ts path is the file, anything else a directory", () => {
	expect(outputFile("/x/db.ts")).toBe("/x/db.ts");
	expect(outputFile("/x/db.mts")).toBe("/x/db.mts");
	expect(outputFile("/x/db.cts")).toBe("/x/db.cts");
	expect(outputFile("/x/generated")).toBe("/x/generated/index.ts");
	expect(outputFile("/x/db.tsx")).toBe("/x/db.tsx/index.ts");
	expect(outputFile("/x/db.d.ts.d")).toBe("/x/db.d.ts.d/index.ts");
});

const options = (
	provider: string,
	config: GeneratorOptions["generator"]["config"] = {},
): GeneratorOptions => ({
	generator: { name: "typesql", output: { value: "/x/db.ts" }, config },
	datamodel: "",
	dmmf: { datamodel: { models: [], enums: [] } },
	schemaPath: "/x/schema.prisma",
	datasources: [{ provider, activeProvider: provider }],
});

test("sourceFor reads the generator config and rejects other providers", () => {
	expect(sourceFor(options("postgresql", { typeName: "Schema" }))).toContain(
		"export interface Schema {",
	);
	expect(() => sourceFor(options("mysql"))).toThrow(
		'typesql-prisma: only the postgresql provider is supported (got "mysql")',
	);
	expect(sourceFor(options("postgres"))).toContain("export interface DB {");
});

test("sourceFor: the provider is the active one, else the declared one, and may be absent", () => {
	const withDatasources = (
		datasources: GeneratorOptions["datasources"],
	): GeneratorOptions => ({ ...options("postgresql"), datasources });
	expect(() =>
		sourceFor(
			withDatasources([{ provider: "postgresql", activeProvider: "mysql" }]),
		),
	).toThrow('(got "mysql")');
	expect(() => sourceFor(withDatasources([{ provider: "sqlite" }]))).toThrow(
		'(got "sqlite")',
	);
	expect(sourceFor(withDatasources([]))).toContain("export interface DB {");
});

test("sourceFor: importFrom and typeName apply when they are strings", () => {
	const withModel = (
		config: GeneratorOptions["generator"]["config"],
	): GeneratorOptions => ({
		...options("postgresql", config),
		datamodel: "view V {\n}\n",
		dmmf: {
			datamodel: {
				models: [{ name: "V", dbName: null, fields: [field("id", "Int")] }],
				enums: [],
			},
		},
	});
	expect(sourceFor(withModel({ importFrom: "./core.js", typeName: "S" }))).toBe(
		`// Generated by @typesql/prisma from the Prisma schema. Do not edit.
import type { Col, View } from "./core.js";

export interface S {
  V: View<{
    id: Col<"int4">;
  }>;
}
`,
	);
	expect(
		sourceFor(withModel({ importFrom: ["./a.js"], typeName: ["A", "B"] })),
	).toBe(
		`// Generated by @typesql/prisma from the Prisma schema. Do not edit.
import type { Col, View } from "@typesql/core";

export interface DB {
  V: View<{
    id: Col<"int4">;
  }>;
}
`,
	);
});

describe("generator.onGenerate", () => {
	const withOutput = (
		output: GeneratorOptions["generator"]["output"],
	): GeneratorOptions => {
		const o = options("postgresql");
		return { ...o, generator: { ...o.generator, output } };
	};

	test("needs an output", async () => {
		const message =
			'typesql-prisma: set `output` in the generator block, e.g. output = "../src/db/typesql.ts"';
		await expect(generator.onGenerate(withOutput(null))).rejects.toThrow(
			message,
		);
		await expect(
			generator.onGenerate(withOutput({ value: null })),
		).rejects.toThrow(message);
		await expect(
			generator.onGenerate(withOutput({ value: "" })),
		).rejects.toThrow(message);
	});

	test("writes the file, creating its directories", async () => {
		const dir = await mkdtemp(join(tmpdir(), "typesql-prisma-"));
		try {
			await generator.onGenerate(withOutput({ value: join(dir, "a/b") }));
			expect(await readFile(join(dir, "a/b/index.ts"), "utf8")).toBe(
				sourceFor(options("postgresql")),
			);
			await generator.onGenerate(withOutput({ value: join(dir, "a/b") }));
		} finally {
			await rm(dir, { recursive: true, force: true });
		}
	});
});

describe("serveGenerator", () => {
	async function exchange(
		handler: GeneratorHandler,
		requests: readonly string[],
	): Promise<unknown[]> {
		const input = new PassThrough();
		const output = new PassThrough();
		let text = "";
		output.on("data", (chunk: Buffer) => (text += chunk.toString()));
		const done = serveGenerator(handler, input, output);
		for (const r of requests) input.write(r + "\n");
		input.end();
		await done;
		return text
			.trim()
			.split("\n")
			.map((l) => (l.startsWith("{") ? JSON.parse(l) : l));
	}

	test("answers getManifest and generate on the output stream, one JSON line each", async () => {
		const seen: string[] = [];
		const handler: GeneratorHandler = {
			onManifest: (config) => (seen.push(config.name), { prettyName: "x" }),
			onGenerate: async (o) => void seen.push(o.schemaPath),
		};
		const res = await exchange(handler, [
			JSON.stringify({
				jsonrpc: "2.0",
				id: 1,
				method: "getManifest",
				params: { name: "typesql" },
			}),
			JSON.stringify({
				jsonrpc: "2.0",
				id: 2,
				method: "generate",
				params: { schemaPath: "/s.prisma" },
			}),
		]);
		expect(res).toEqual([
			{ jsonrpc: "2.0", id: 1, result: { manifest: { prettyName: "x" } } },
			{ jsonrpc: "2.0", id: 2, result: null },
		]);
		expect(seen).toEqual(["typesql", "/s.prisma"]);
	});

	test("a thrown non-Error is reported with its text", async () => {
		const handler: GeneratorHandler = {
			onManifest: () => {
				throw "no manifest";
			},
			onGenerate: () => {},
		};
		const res = await exchange(handler, [
			JSON.stringify({
				jsonrpc: "2.0",
				id: 3,
				method: "getManifest",
				params: {},
			}),
		]);
		expect(res).toEqual([
			{
				jsonrpc: "2.0",
				id: 3,
				error: {
					code: -32000,
					message: "no manifest",
					data: { stack: expect.stringContaining("Error: no manifest") },
				},
			},
		]);
	});

	test("reports handler failures and unknown methods as JSON-RPC errors", async () => {
		const handler: GeneratorHandler = {
			onManifest: () => ({}),
			onGenerate: () => {
				throw new Error("boom");
			},
		};
		const res = await exchange(handler, [
			JSON.stringify({ jsonrpc: "2.0", id: 7, method: "generate", params: {} }),
			JSON.stringify({ jsonrpc: "2.0", id: 8, method: "nope", params: {} }),
			"not json",
			"",
			" \t ",
		]);
		// Responses are matched by id, so their order does not matter. Blank lines are skipped.
		expect(res).toHaveLength(3);
		expect(res).toContainEqual({
			jsonrpc: "2.0",
			id: 7,
			error: {
				code: -32000,
				message: "boom",
				data: { stack: expect.stringContaining("boom") },
			},
		});
		expect(res).toContainEqual({
			jsonrpc: "2.0",
			id: 8,
			error: { code: -32601, message: "Method not found: nope" },
		});
		expect(res).toContain(
			"typesql-prisma: ignoring a request that is not JSON: not json",
		);
	});
});

const pkg = fileURLToPath(new URL("..", import.meta.url));
const run = promisify(execFile);

test("prisma generate runs the generator end to end", {
	timeout: 60_000,
}, async () => {
	// A copy of the fixture schema, so the output lands in a temporary directory.
	const dir = await mkdtemp(join(tmpdir(), "typesql-prisma-"));
	try {
		await copyFile(
			join(pkg, "test/fixtures/schema.prisma"),
			join(dir, "schema.prisma"),
		);
		const prisma = join(pkg, "node_modules/.bin/prisma");
		const { stdout } = await run(
			prisma,
			[
				"generate",
				"--schema",
				join(dir, "schema.prisma"),
				"--generator",
				"typesql",
				"--no-hints",
			],
			{
				cwd: pkg,
				env: { ...process.env, CHECKPOINT_DISABLE: "1" },
			},
		);
		expect(stdout).toContain("Generated TypeSQL schema");
		await expect(
			await readFile(join(dir, "typesql.ts"), "utf8"),
		).toMatchFileSnapshot("./fixtures/typesql.ts");
	} finally {
		await rm(dir, { recursive: true, force: true });
	}
});
